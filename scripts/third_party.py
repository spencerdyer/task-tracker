#!/usr/bin/env python3
"""Write docs/THIRD_PARTY.md: the licence of every runtime dependency (server and web).

Run from the repository root after installing both (server/.venv and web/node_modules):
    server/.venv/bin/python scripts/third_party.py
"""
import importlib.metadata as md
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SKIP = {"task-tracker", "pip", "setuptools", "wheel", "pytest", "iniconfig", "pluggy", "packaging", "httpx",
        "httpcore", "certifi", "idna"}  # the tool itself, installers and test-only packages


def py_rows():
    for d in sorted(md.distributions(), key=lambda d: d.metadata["Name"].lower()):
        name = d.metadata["Name"]
        if name.lower() in SKIP:
            continue
        lic = d.metadata.get("License-Expression") or ""
        if not lic:
            cls = [c.split("::")[-1].strip() for c in (d.metadata.get_all("Classifier") or []) if c.startswith("License ::")]
            lic = "; ".join(cls) or (d.metadata.get("License") or "").split("\n")[0][:60]
        yield name, d.version, lic


def web_rows():
    lock = json.loads((ROOT / "web" / "package-lock.json").read_text())
    for path, info in sorted(lock["packages"].items()):
        if not path or info.get("dev"):
            continue
        name = path.split("node_modules/")[-1]
        lic = info.get("license")
        if not lic:
            pkg = ROOT / "web" / path / "package.json"
            lic = json.loads(pkg.read_text()).get("license") if pkg.exists() else "?"
        yield name, info.get("version", "?"), lic or "?"


def table(rows):
    out = ["| Package | Version | Licence |", "| --- | --- | --- |"]
    out += [f"| {n} | {v} | {l} |" for n, v, l in rows]
    return "\n".join(out)


doc = f"""# Third-party software

Task Tracker is licensed under the Apache License 2.0. It uses the packages below, each under its own
licence (the licence texts ship inside each package). Generated by `scripts/third_party.py`.

## Fonts (bundled in the web app)

Instrument Sans, Newsreader and Geist Mono, via the `@fontsource-variable` packages, under the SIL Open
Font License 1.1.

## Copied code

- `web/src/styles/preflight-v3.css`: Tailwind CSS v3's base styles, MIT licence (Tailwind Labs, Inc.).

## Server (Python, runtime)

{table(py_rows())}

## Web app (npm, runtime)

{table(web_rows())}
"""
(ROOT / "docs" / "THIRD_PARTY.md").write_text(doc)
print("wrote docs/THIRD_PARTY.md")
